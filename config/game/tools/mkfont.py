FIRST, LAST = 32, 126


def rows(art):
    parts = art.split()
    if len(parts) != H:
        raise SystemExit("glyph needs %d rows, got %d: %r" % (H, len(parts), art))
    out = []
    for r in parts:
        if len(r) != W:
            raise SystemExit("row needs %d columns: %r" % (W, r))
        # bit 7 is the leftmost pixel, matching the framebuffer's MSB-first order
        out.append(sum(0x80 >> i for i, c in enumerate(r) if c == "#"))
    return out


def main():
    blank = rows(GLYPHS[" "])
    lines = [
        "/* Generated by tools/mkfont.py — edit the glyph art there, not this file. */",
        "",
        '#include "totem_game.h"',
        "",
        "const uint8_t game_font5x7[GAME_FONT_COUNT][GAME_FONT_H] = {",
    ]
    missing = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        art = GLYPHS.get(ch)
        if art is None and ch.isalpha():
            art = GLYPHS.get(ch.upper())  # lowercase falls back to caps
        if art is None:
            missing.append(ch)
            data = blank
        else:
            data = rows(art)
        lines.append(
            "    { %s }, /* %s */"
            % (", ".join("0x%02x" % b for b in data), ch if ch != " " else "space")
        )
    lines.append("};")
    lines.append("")

    open(sys.argv[1], "w").write("\n".join(lines))
    print("wrote %s: %d glyphs, %d blank (%s)" % (
        sys.argv[1], LAST - FIRST + 1, len(missing), "".join(missing)))


if __name__ == "__main__":
    main()
